def execution_owner(record, key):
    """Each source context is assigned independently from the candidate manifest."""
    ident = record['id'].split('character/')[1]
    tail = ident.split('/')[-1]
    if record['kind'] == 'level':
        return 'level-' + str(record['level'])
    if '/metamagic/' in ident:
        for option in ('careful', 'distant', 'empowered', 'extended', 'heightened', 'quickened', 'seeking', 'subtle', 'transmuted', 'twinned'):
            if option + '-spell' in ident:
                return option + '-spell'
    if '/draconic-sorcery/' in ident:
        if 'identity' in tail:
            return 'sorcerer-subclass'
        if 'draconic-resilience' in tail:
            return 'draconic-ac' if '/base-ac-' in key else 'draconic-hp'
        if 'draconic-spells' in tail:
            return 'draconic-spells'
        if 'elemental-affinity' in tail:
            return 'affinity-damage' if 'damage-roll' in key else 'elemental-affinity'
        if 'dragon-wings' in tail:
            return 'wings-recovery' if any(s in key for s in ['restore', 'reuse/', 'uses']) else 'dragon-wings'
        if 'dragon-companion' in tail:
            return 'companion-modification' if 'concentration' in key or 'duration' in key else 'companion-casting'
    if record['kind'] == 'class':
        return 'hp' if 'hit-die' in key else 'proficiencies'
    if tail in ['entry', 'first-class-traits', 'first-class-entry']:
        return 'later-entry' if key.endswith('/multiclass') else 'creation'
    if tail in ['multiclass-traits', 'multiclass-entry']:
        return 'later-entry'
    if tail == 'skills':
        return 'proficiencies'
    if tail == 'starting-equipment':
        return 'equipment'
    if tail == 'spellcasting':
        if 'cantrip' in key:
            return 'cantrips'
        if any(s in key for s in ['prepared', 'recommended-spell']):
            return 'preparation'
        return 'spellcasting'
    if tail in ['cantrips', 'prepared-spells', 'prepared-slot-level', 'initial-prepared-level']:
        return 'cantrips' if tail == 'cantrips' else 'preparation'
    if tail.startswith('spell-slot-'):
        return 'slots'
    if tail == 'innate-sorcery':
        if record['kind'] == 'resource':
            return 'innate-recovery'
        return 'innate-benefits' if any(s in key for s in ['dc-increase', 'advantage-']) else 'innate-activation'
    if tail == 'font-of-magic':
        if 'expend-slot-gain' in key:
            return 'slot-to-points'
        if 'vanishes' in key:
            return 'created-slot-ending'
        if 'capped' in key:
            return 'points'
        return 'points-to-slot'
    if tail == 'sorcery-points':
        return 'points'
    if tail == 'metamagic':
        return 'metamagic-selection' if record['kind'] == 'choice' or 'replace' in key else 'metamagic-combination'
    if tail in ['subclass', 'sorcerer-subclass']:
        return 'sorcerer-subclass'
    if tail.startswith('ability-score-improvement'):
        return 'ability-score-improvement'
    if tail.startswith('epic-boon'):
        return 'epic-boon'
    if tail == 'sorcerous-restoration':
        return 'restoration-reset' if record['kind'] == 'resource' or 'once-until' in key else 'sorcerous-restoration'
    if tail in ['sorcery-incarnate', 'incarnate-no-uses', 'incarnate-active']:
        return 'incarnate-combination' if 'active' in tail or 'options-per-spell' in key or 'two-metamagic' in key else 'incarnate-activation'
    if tail in ['arcane-apotheosis', 'apotheosis-active']:
        return 'arcane-apotheosis'
    raise AssertionError('unowned source context ' + ident)


